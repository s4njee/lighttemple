#!/usr/bin/env node
/**
 * Imports the GGX linearly-transformed-cosine (LTC) lookup tables into src/gpu/ltc-data.ts.
 *
 *   node scripts/import-ltc.mjs <path/to/three/examples/jsm/lights/RectAreaLightTexturesLib.js>
 *
 * The tables are the fit results of Heitz, Dupuy, Hill & Neubelt, "Real-Time Polygonal-Light
 * Shading with Linearly Transformed Cosines" (SIGGRAPH 2016), as published in
 * https://github.com/selfshadow/ltc_code (fit/results/ltc.js) and redistributed by three.js
 * (MIT licence) in RectAreaLightTexturesLib.js. Nothing is downloaded: point the script at a
 * local copy of that file (any three.js >= r150 install has it).
 *
 * Two 64×64 RGBA tables, indexed by (perceptual roughness, sqrt(1 - cos θv)):
 *   ltc1 = (a, b, c, d): the inverse LTC matrix  [a 0 c; 0 1 0; b 0 d]  (columns (a,0,b), (0,1,0), (c,0,d))
 *   ltc2 = (n, f, 0, s): GGX magnitude n and Fresnel term f (specular = F0·n + (1 − F0)·f, Hill 2016),
 *          and in .w a *different* table indexed by (z·0.5 + 0.5, |F|): the horizon-clipped sphere
 *          form factor ratio used by the "clipless" approximation (Hill & Heitz 2016/2017).
 *
 * Output: float16 (little-endian) as base64, ltc1 then ltc2 (64 KiB raw). Half floats keep every
 * entry within 0.05 % (relative, |x| > 1e-3) of the source; the script prints the worst error.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SIZE = 64;
const source = process.argv[2];
if (!source) {
  console.error('usage: node scripts/import-ltc.mjs <path/to/RectAreaLightTexturesLib.js>');
  process.exit(1);
}

const text = readFileSync(source, 'utf8');
const grab = (name) => {
  const m = text.match(new RegExp(`const ${name} = (\\[[^\\]]*\\])`));
  if (!m) throw new Error(`${name} not found in ${source}`);
  // three.js formats negatives as "- 4.48815e-07".
  const values = JSON.parse(m[1].replace(/-\s+/g, '-'));
  if (values.length !== SIZE * SIZE * 4) throw new Error(`${name}: expected ${SIZE * SIZE * 4} values, got ${values.length}`);
  return values;
};

/** float32 -> float16 bits, round to nearest even (handles subnormals; no NaN/Inf in this data). */
function toHalf(value) {
  const f32 = new Float32Array([value]);
  const bits = new Uint32Array(f32.buffer)[0];
  const sign = (bits >>> 16) & 0x8000;
  const exp = ((bits >>> 23) & 0xff) - 127 + 15;
  let mant = bits & 0x7fffff;
  if (exp >= 31) return sign | 0x7c00;
  if (exp <= 0) {
    if (exp < -10) return sign;
    mant |= 0x800000;
    const shift = 14 - exp;
    let half = mant >>> shift;
    const rem = mant & ((1 << shift) - 1);
    const mid = 1 << (shift - 1);
    if (rem > mid || (rem === mid && half & 1)) half++;
    return sign | half;
  }
  let half = (exp << 10) | (mant >>> 13);
  const rem = mant & 0x1fff;
  if (rem > 0x1000 || (rem === 0x1000 && half & 1)) half++;
  return sign | half;
}

function fromHalf(h) {
  const s = h & 0x8000 ? -1 : 1;
  const e = (h >>> 10) & 0x1f;
  const m = h & 0x3ff;
  if (e === 0) return s * m * 2 ** -24;
  return s * (1 + m / 1024) * 2 ** (e - 15);
}

const tables = [grab('LTC_MAT_1'), grab('LTC_MAT_2')];
const halves = new Uint16Array(tables.length * SIZE * SIZE * 4);
let worst = 0;
tables.flat().forEach((v, i) => {
  halves[i] = toHalf(v);
  worst = Math.max(worst, Math.abs(fromHalf(halves[i]) - v) / Math.max(Math.abs(v), 1e-3));
});
const bytes = Buffer.from(halves.buffer); // little-endian on every platform Node runs on
const base64 = bytes.toString('base64');

const out = join(dirname(fileURLToPath(import.meta.url)), '../src/gpu/ltc-data.ts');
writeFileSync(
  out,
  `/**
 * GENERATED by scripts/import-ltc.mjs. Do not edit.
 *
 * GGX LTC fit tables from Heitz, Dupuy, Hill & Neubelt, "Real-Time Polygonal-Light Shading with
 * Linearly Transformed Cosines" (SIGGRAPH 2016), https://github.com/selfshadow/ltc_code
 * (fit/results/ltc.js), as redistributed by three.js (MIT licence, (c) 2010-2024 three.js
 * authors) in examples/jsm/lights/RectAreaLightTexturesLib.js. See public/assets/CREDITS.md.
 *
 * ${SIZE}×${SIZE} rgba float16, little-endian, base64: ltc1 (inverse matrix a, b, c, d) then ltc2
 * (magnitude, Fresnel, 0, clipped-sphere ratio). See src/gpu/ltc.ts for the layout.
 */

export const LTC_SIZE = ${SIZE};

export const LTC_HALF_BASE64 =
  '${base64}';
`,
);
console.log(`wrote ${out}: ${bytes.length} bytes as ${base64.length} base64 chars; worst float16 error ${(worst * 100).toFixed(3)} %`);
