/**
 * Linearly transformed cosine (LTC) lookup tables for analytic GGX area lights
 * (Heitz, Dupuy, Hill & Neubelt 2016), uploaded once as two 64×64 `rgba16float` textures.
 *
 *   const ltc = createLtcTables(device);
 *   // bind ltc.matrix, ltc.magnitude (texture_2d<f32>, filterable) and ltc.sampler, then in WGSL:
 *   //   wgsl(commonWgsl, ltcWgsl, ...)
 *   //   let lobe = ltc_lobe(ltc_matrix, ltc_magnitude, ltc_sampler, n, v, roughness);
 *   //   let spec = ltc_polygon(ltc_magnitude, ltc_sampler, lobe.m * (c - p), lobe.m * ex, lobe.m * ey, ...);
 *   ltc.destroy();
 *
 * Layout, both indexed by uv = (perceptual roughness, sqrt(1 - N·V)) with half-texel bias:
 *   matrix    (a, b, c, d): inverse LTC matrix, columns (a, 0, b), (0, 1, 0), (c, 0, d), in the
 *             (T1, T2, N) frame where T1 lies in the plane of N and V
 *   magnitude (n, f, 0, s): specular albedo = F0·n + (1 − F0)·f (Hill's LTC Fresnel), and in .w a
 *             separate table indexed by (z·0.5 + 0.5, |F|): the horizon-clipped sphere ratio
 *
 * The data (src/gpu/ltc-data.ts) is generated by scripts/import-ltc.mjs from the fit published
 * with the paper, as redistributed by three.js (MIT). Half floats are within 0.05 % of the
 * source everywhere, so the tables are always 16-bit: `rgba16float` is filterable in core
 * WebGPU, and `rgba32float` (which needs `float32-filterable`) would buy nothing visible.
 */

import ltcWgsl from '../shaders/ltc.wgsl?raw';
import { LTC_HALF_BASE64, LTC_SIZE } from './ltc-data';

export { ltcWgsl };

export interface LtcTables {
  /** Inverse LTC matrix entries (a, b, c, d). */
  matrix: GPUTexture;
  /** (GGX magnitude, Fresnel, 0, clipped-sphere ratio). */
  magnitude: GPUTexture;
  /** Bilinear, clamp-to-edge. */
  sampler: GPUSampler;
  destroy(): void;
}

export function createLtcTables(device: GPUDevice): LtcTables {
  const raw = atob(LTC_HALF_BASE64);
  const bytes = new Uint8Array(raw.length);
  for (let i = 0; i < raw.length; i++) bytes[i] = raw.charCodeAt(i);
  const tableBytes = LTC_SIZE * LTC_SIZE * 8;

  const upload = (label: string, offset: number) => {
    const texture = device.createTexture({
      label,
      size: [LTC_SIZE, LTC_SIZE],
      format: 'rgba16float',
      usage: GPUTextureUsage.TEXTURE_BINDING | GPUTextureUsage.COPY_DST,
    });
    device.queue.writeTexture({ texture }, bytes.subarray(offset, offset + tableBytes), { bytesPerRow: LTC_SIZE * 8 }, [LTC_SIZE, LTC_SIZE]);
    return texture;
  };
  const matrix = upload('ltc-matrix', 0);
  const magnitude = upload('ltc-magnitude', tableBytes);
  const sampler = device.createSampler({
    label: 'ltc',
    magFilter: 'linear',
    minFilter: 'linear',
    addressModeU: 'clamp-to-edge',
    addressModeV: 'clamp-to-edge',
  });
  return {
    matrix,
    magnitude,
    sampler,
    destroy() {
      matrix.destroy();
      magnitude.destroy();
    },
  };
}
